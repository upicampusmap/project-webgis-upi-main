"""Optional maintainer tool: python scripts/optimize-images.py (requires Pillow).
Creates WebP derivatives and updates photos.js; never replaces source photos.
"""
import json
from pathlib import Path
from PIL import Image, ImageOps

ROOT = Path(__file__).resolve().parents[1]
features = json.loads((ROOT / "data/gedung-upi-point.geojson").read_text(encoding="utf-8-sig"))["features"]
output = ROOT / "images/optimized"
output.mkdir(exist_ok=True)
manifest = {}
for feature in features:
    value = feature.get("properties", {}).get("image")
    if not isinstance(value, str) or not value:
        continue
    relative = value if value.startswith("images/") else "images/" + value
    source = (ROOT / relative).resolve()
    if not source.is_relative_to((ROOT / "images").resolve()) or not source.is_file() or relative in manifest:
        continue
    destination = output / (source.stem + ".webp")
    with Image.open(source) as image:
        image = ImageOps.exif_transpose(image)
        image.thumbnail((1280, 1280), Image.Resampling.LANCZOS)
        image.convert("RGB").save(destination, "WEBP", quality=80, method=6)
    manifest[relative] = "images/optimized/" + destination.name
for name in ["banner.png", "map-preview.png"]:
    source = ROOT / "images" / name
    with Image.open(source) as image:
        image = ImageOps.exif_transpose(image)
        image.thumbnail((1920, 1920), Image.Resampling.LANCZOS)
        image.convert("RGB").save(source.with_suffix(".webp"), "WEBP", quality=82, method=6)
(ROOT / "assets/js/map/photos.js").write_text(
    "// Generated by scripts/optimize-images.py; originals remain in images/.\nexport const optimizedPhotos = " +
    json.dumps(manifest, ensure_ascii=False, indent=2) + ";\n", encoding="utf-8")
print(f"Generated {len(manifest)} campus photo derivatives.")
